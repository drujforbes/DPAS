from pathlib import Path
from playwright.sync_api import sync_playwright
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path=__import__('os').environ.get('DPAS_CHROMIUM_PATH') or ('/usr/bin/chromium' if __import__('os').path.isfile('/usr/bin/chromium') else None),args=['--no-sandbox']);page=b.new_page()
 page.set_content((Path(__file__).parent/'index.html').read_text(),wait_until='load')
 page.evaluate("""() => {window.waiting=[];window.tmdb=path=>new Promise((resolve,reject)=>waiting.push({path,resolve,reject}));window.setImage=async()=>{};window.loadGallery=async()=>{};}""")
 page.evaluate("() => { void selectMedia({media_type:'movie',id:11,title:'Older'}); }")
 page.wait_for_function('waiting.length===1',timeout=5000)
 page.evaluate("() => { void selectMedia({media_type:'movie',id:22,title:'Newer'}); }")
 page.wait_for_function('waiting.length===2',timeout=5000)
 page.evaluate("waiting[1].resolve({production_companies:[{name:'New Studio'}],networks:[]})")
 page.wait_for_function("companyMetadata.production.some(x=>x.name==='New Studio')",timeout=5000)
 page.evaluate("waiting[0].resolve({production_companies:[{name:'Old Studio'}],networks:[]})")
 page.wait_for_timeout(150)
 assert page.evaluate("companyMetadata.production.some(x=>x.name==='New Studio') && !companyMetadata.production.some(x=>x.name==='Old Studio')")
 print('PASS: stale title details cannot overwrite selected company metadata')
 page.evaluate("() => { window.waiting=[]; window.fetchDistributorCandidates=async()=>{}; void selectMedia({media_type:'movie',id:33,title:'Old Error'}); }")
 page.wait_for_function('waiting.length===1',timeout=5000)
 page.evaluate("() => { void selectMedia({media_type:'movie',id:44,title:'Current Title'}); }")
 page.wait_for_function('waiting.length===2',timeout=5000)
 page.evaluate("waiting[1].resolve({production_companies:[{name:'Current Studio'}],networks:[]})")
 page.wait_for_function("companyMetadata.production.some(x=>x.name==='Current Studio')",timeout=5000)
 page.evaluate("waiting[0].reject(new Error('Stale provider error'))")
 page.wait_for_timeout(100)
 assert page.evaluate("companyMetadata.production.some(x=>x.name==='Current Studio')")
 assert 'Stale provider error' not in page.evaluate("document.querySelector('#status')?.textContent||''")
 print('PASS: stale title error cannot overwrite current company metadata or status')
 b.close()

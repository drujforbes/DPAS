from pathlib import Path
from playwright.sync_api import sync_playwright
with sync_playwright() as pw:
 b=pw.chromium.launch(headless=True,executable_path=__import__('os').environ.get('DPAS_CHROMIUM_PATH') or ('/usr/bin/chromium' if __import__('os').path.isfile('/usr/bin/chromium') else None),args=['--no-sandbox'])
 p=b.new_page();p.set_content((Path(__file__).parent/'index.html').read_text())
 p.evaluate('''() => {window.pendingSearch=[];window.fetch=(url)=>new Promise((resolve,reject)=>window.pendingSearch.push({url,resolve,reject}));document.getElementById('token').value='test';}''')
 p.locator('#query').fill('First');p.evaluate('() => {search();}')
 p.locator('#query').fill('Second');p.evaluate('() => {search();}')
 p.wait_for_function('pendingSearch.length===2')
 p.evaluate('''() => pendingSearch[1].resolve({ok:true,json:async()=>({results:[{media_type:'movie',title:'Second Movie',id:2}]})})''')
 p.wait_for_function("document.getElementById('results').textContent.includes('Second Movie')")
 p.evaluate('''() => pendingSearch[0].resolve({ok:true,json:async()=>({results:[{media_type:'movie',title:'First Movie',id:1}]})})''')
 p.wait_for_timeout(100)
 assert 'Second Movie' in p.locator('#results').inner_text()
 assert 'First Movie' not in p.locator('#results').inner_text()
 print('PASS: outdated successful search cannot replace newer results')
 p.locator('#query').fill('Third');p.evaluate('() => {search();}')
 p.locator('#query').fill('Fourth');p.evaluate('() => {search();}')
 p.wait_for_function('pendingSearch.length===4')
 p.evaluate('''() => pendingSearch[3].resolve({ok:true,json:async()=>({results:[{media_type:'movie',title:'Fourth Movie',id:4}]})})''')
 p.wait_for_function("document.getElementById('results').textContent.includes('Fourth Movie')")
 p.evaluate('''() => pendingSearch[2].reject(new Error('Old request failed'))''')
 p.wait_for_timeout(100)
 assert 'Fourth Movie' in p.locator('#results').inner_text()
 assert 'Old request failed' not in p.locator('body').inner_text()
 print('PASS: outdated failed search cannot overwrite current results/status')
 b.close()

from pathlib import Path
from playwright.sync_api import sync_playwright
with sync_playwright() as pw:
 browser=pw.chromium.launch(headless=True,executable_path=__import__('os').environ.get('DPAS_CHROMIUM_PATH') or ('/usr/bin/chromium' if __import__('os').path.isfile('/usr/bin/chromium') else None),args=['--no-sandbox'])
 page=browser.new_page()
 page.set_content((Path(__file__).parent/'index.html').read_text(),wait_until='load')
 page.locator('#openSourceSettings').click()
 page.evaluate('''() => {window.connectionRequests=[];window.fetch=(url,options)=>new Promise(resolve=>{window.connectionRequests.push({url,resolve})})}''')
 cards=page.locator('#providerSettings .provider')
 card=cards.filter(has=page.locator('h3',has_text='TMDB')).first
 field=card.locator('input[type=password]'); test=card.get_by_role('button',name='Test connection');clear=card.get_by_role('button',name='Clear key')
 field.fill('old-key');test.click();page.wait_for_function('connectionRequests.length===1')
 assert test.is_disabled()
 field.fill('new-key')
 page.evaluate('connectionRequests[0].resolve({ok:true,status:200})')
 page.wait_for_timeout(100)
 assert 'Connected to TMDB successfully' not in card.locator('.source-status').inner_text()
 print('PASS: obsolete success cannot verify a changed credential')
 test.click();page.wait_for_function('connectionRequests.length===2')
 clear.click()
 page.evaluate('connectionRequests[1].resolve({ok:true,status:200})')
 page.wait_for_timeout(100)
 assert 'Credential cleared' in card.locator('.source-status').inner_text()
 assert test.is_enabled()
 print('PASS: clearing credentials invalidates in-flight connection test')
 field.fill('current-key');test.click();page.wait_for_function('connectionRequests.length===3')
 page.evaluate('connectionRequests[2].resolve({ok:true,status:200})')
 page.wait_for_function("document.querySelector('#sourceStatus_tmdb').textContent.includes('Connected to TMDB successfully')")
 assert test.is_enabled()
 print('PASS: current credential can be verified after retry')
 browser.close()
